#!/usr/bin/env bash

# Resolves the configured maintenance branches and updates dependencies.lock.
# Normal builds never follow branch heads; run this command intentionally.

set -euo pipefail

TOOLS_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROCKCHIP_BUILD_DIR=$(cd -- "$TOOLS_DIR/.." && pwd)
source "$ROCKCHIP_BUILD_DIR/config.sh"
source "$ROCKCHIP_BUILD_DIR/lib/git-helpers.sh"

lock_file="$ROCKCHIP_BUILD_DIR/dependencies.lock"
temporary_lock=$(mktemp "$ROCKCHIP_BUILD_DIR/.dependencies.lock.XXXXXX")
trap 'rm -f -- "$temporary_lock"' EXIT

mpp_sha=$(git_branch_sha "$MPP_REPOSITORY" "$MPP_BRANCH")
rga_sha=$(git_branch_sha "$RGA_REPOSITORY" "$RGA_BRANCH")

for dependency_sha in "$mpp_sha" "$rga_sha"; do
  if [[ ! "$dependency_sha" =~ ^[0-9a-f]{40}$ ]]; then
    printf 'Invalid dependency revision: %s\n' "$dependency_sha" >&2
    exit 1
  fi
done

{
  printf '%s\n' \
    '# Generated by update-dependencies.sh. Commit changes to this file intentionally.'
  printf 'ROCKCHIP_LOCKED_MPP_SHA=%s\n' "$mpp_sha"
  printf 'ROCKCHIP_LOCKED_RGA_SHA=%s\n' "$rga_sha"
} >"$temporary_lock"

chmod 0644 "$temporary_lock"
mv -- "$temporary_lock" "$lock_file"
trap - EXIT

printf 'Updated %s\n' "$lock_file"
printf 'MPP %s (%s)\n' "$mpp_sha" "$MPP_BRANCH"
printf 'RGA %s (%s)\n' "$rga_sha" "$RGA_BRANCH"
